// Gerber Exporter — génération ZIP Gerber simulé
// V8-D-13-a

import JSZip from 'jszip';

export interface GerberExportOptions {
  projectId: string;
  layers?: string[];
}

const DEFAULT_LAYERS = ['F.Cu', 'B.Cu', 'F.SilkS', 'B.SilkS', 'Edge.Cuts'];

export async function generateGerberZip(options: GerberExportOptions): Promise<Buffer> {
  const layers = options.layers || DEFAULT_LAYERS;
  const zip = new JSZip();

  // Simulation : chaque couche = fichier texte placeholder
  for (const layer of layers) {
    const content = `G04 Layer: ${layer} - Project: ${options.projectId}\nG04 Generated by PartIVA PCB Studio\nM02`;
    zip.file(`${options.projectId}-${layer}.gbr`, content);
  }

  // Fichier de drill simulé
  zip.file(`${options.projectId}-drill.drl`, 'M48\n%MOIN*%\nT1C0.0125\nT2C0.025\nM30');

  const buffer = await zip.generateAsync({ type: 'nodebuffer' });
  return buffer;
}
